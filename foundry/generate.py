"""Deterministic artifact generators: spec -> SQL / C++ / Lua / DBC / conf.

Determinism contract: same spec bytes in, same artifact bytes out. No
timestamps, no randomness, sorted iteration everywhere. Timestamps are
opt-in (``--stamp``) and live only in the manifest, never in content files.

Generated SQL is idempotent (DELETE-before-INSERT per entry) and every
INSERT has a matching DELETE in the rollback file — the test suite proves
both properties mechanically.
"""

from __future__ import annotations

import json
from typing import Dict, List, Optional

from .spec import allocate_ids


def _sql_str(value) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, (int, float)):
        return repr(value)
    return "'" + str(value).replace("\\", "\\\\").replace("'", "\\'") + "'"


def _ref(obj: dict, field: str):
    """Asset ref value + TODO marker when unverified."""
    ref = obj.get(field)
    if isinstance(ref, dict):
        return ref.get("value"), not ref.get("verified")
    return ref, False


def _todo(unverified: bool) -> str:
    return " -- TODO(verify): confirm this id in your own client data" if unverified else ""


def world_sql(spec: dict, *, reserved=None) -> str:
    """World-DB migration for the spec's objects. Deterministic order."""
    ids = allocate_ids(spec, reserved=reserved)
    lines = [
        f"-- {spec.get('title', spec.get('name'))} — world migration (generated by Arena Foundry)",
        f"-- spec: {spec.get('name')} v{spec.get('version')} (spec_version {spec.get('spec_version')})",
        "-- Idempotent: DELETE-before-INSERT per entry. Rollback: 99_rollback.sql.",
        "",
    ]
    # items
    items = spec.get("items") or []
    if items:
        lines.append("-- items (item_template)")
        for obj in items:
            eid = ids[obj["key"]]
            disp, unv = _ref(obj, "display_id")
            lines.append(f"DELETE FROM item_template WHERE entry = {eid};")
            lines.append(
                f"INSERT INTO item_template (entry, name, description, VerifiedBuild) VALUES "
                f"({eid}, {_sql_str(obj.get('name'))}, {_sql_str(obj.get('description', ''))}, 12340);"
                f"{_todo(unv)}")
            if disp is not None:
                lines.append(
                    f"-- display_id {disp} must already exist in ItemDisplayInfo.dbc "
                    f"(patch cost: {'none' if not unv else 'dbc-rows if missing'}){_todo(unv)}")
        lines.append("")
    # spells (server overlay)
    spells = spec.get("spells") or []
    if spells:
        lines.append("-- spells (spell_dbc overlay; visual/icon must already exist client-side)")
        for obj in spells:
            sid = ids[obj["key"]]
            lines.append(f"DELETE FROM spell_dbc WHERE Id = {sid};")
            lines.append(
                f"INSERT INTO spell_dbc (Id, Name) VALUES ({sid}, {_sql_str(obj.get('name'))});")
        lines.append("")
    # quests
    quests = spec.get("quests") or []
    if quests:
        lines.append("-- quests (quest_template)")
        for obj in quests:
            qid = ids[obj["key"]]
            lines.append(f"DELETE FROM quest_template WHERE Id = {qid};")
            lines.append(
                f"INSERT INTO quest_template (Id, Title, Objectives, VerifiedBuild) VALUES "
                f"({qid}, {_sql_str(obj.get('title'))}, {_sql_str(obj.get('objectives', ''))}, 12340);")
        lines.append("")
    # creatures
    creatures = spec.get("creatures") or []
    if creatures:
        lines.append("-- creatures (creature_template + model)")
        for obj in creatures:
            cid = ids[obj["key"]]
            disp, unv = _ref(obj, "display_id")
            lines.append(f"DELETE FROM creature_template_model WHERE CreatureID = {cid};")
            lines.append(f"DELETE FROM creature_template WHERE entry = {cid};")
            lines.append(
                f"INSERT INTO creature_template (entry, name, minlevel, maxlevel, VerifiedBuild) "
                f"VALUES ({cid}, {_sql_str(obj.get('name'))}, {obj.get('minlevel', 1)}, "
                f"{obj.get('maxlevel', 1)}, 12340);")
            if disp is not None:
                lines.append(
                    f"INSERT INTO creature_template_model (CreatureID, Idx, CreatureDisplayID, "
                    f"DisplayScale, Probability, VerifiedBuild) VALUES ({cid}, 0, {disp}, 1.0, 1, 12340);"
                    f"{_todo(unv)}")
        lines.append("")
    # vendors
    vendors = spec.get("vendors") or []
    if vendors:
        lines.append("-- vendors (npc_vendor)")
        for obj in vendors:
            cid = ids[obj["creature_key"]]
            for row in obj.get("rows") or []:
                iid = ids[row["item_key"]]
                lines.append(
                    f"DELETE FROM npc_vendor WHERE entry = {cid} AND item = {iid};")
                lines.append(
                    f"INSERT INTO npc_vendor (entry, slot, item, maxcount, incrtime, "
                    f"ExtendedCost, VerifiedBuild) VALUES ({cid}, {row.get('slot', 1)}, {iid}, "
                    f"{row.get('maxcount', 0)}, {row.get('incrtime', 0)}, 0, 12340);")
        lines.append("")
    # recipes -> spell_dbc rows are the spell objects; emit a comment map
    recipes = spec.get("recipes") or []
    if recipes:
        lines.append("-- recipes (crafting: result <- ingredients; deterministic identity)")
        for obj in recipes:
            result = ids[obj["result_key"]]
            ings = ", ".join(f"{ids[i['item_key']]}x{i.get('count', 1)}"
                             for i in obj.get("ingredients") or [])
            lines.append(f"-- recipe {obj['key']}: produces item {result} from {ings}")
        lines.append("")
    # events
    events = spec.get("events") or []
    if events:
        lines.append("-- world events (game_event; eventEntry is tinyint 0-255)")
        for obj in events:
            eid = ids[obj["key"]]
            lines.append(f"DELETE FROM game_event WHERE eventEntry = {eid};")
            lines.append(
                f"INSERT INTO game_event (eventEntry, start_time, end_time, occurence, length, "
                f"description, world_event, announce) VALUES ({eid}, {_sql_str(obj.get('start_time', ''))}, "
                f"{_sql_str(obj.get('end_time', ''))}, {obj.get('occurence', 10080)}, "
                f"{obj.get('length', 60)}, {_sql_str(obj.get('name', ''))}, 0, 1);")
        lines.append("")
    if len(lines) <= 4:
        lines.append("-- (no world objects in this spec)")
    return "\n".join(lines)


def rollback_sql(spec: dict, *, reserved=None) -> str:
    """DELETEs mirroring world_sql, in reverse table order."""
    ids = allocate_ids(spec, reserved=reserved)
    lines = [
        f"-- {spec.get('title', spec.get('name'))} — rollback (generated by Arena Foundry)",
        "-- Removes every row the migration inserts, by entry. Safe to run twice.",
        "",
    ]
    for obj in spec.get("events") or []:
        lines.append(f"DELETE FROM game_event WHERE eventEntry = {ids[obj['key']]};")
    for obj in spec.get("vendors") or []:
        cid = ids[obj["creature_key"]]
        for row in obj.get("rows") or []:
            lines.append(f"DELETE FROM npc_vendor WHERE entry = {cid} AND item = {ids[row['item_key']]};")
    for obj in spec.get("creatures") or []:
        cid = ids[obj["key"]]
        lines.append(f"DELETE FROM creature_template_model WHERE CreatureID = {cid};")
        lines.append(f"DELETE FROM creature_template WHERE entry = {cid};")
    for obj in spec.get("quests") or []:
        lines.append(f"DELETE FROM quest_template WHERE Id = {ids[obj['key']]};")
    for obj in spec.get("spells") or []:
        lines.append(f"DELETE FROM spell_dbc WHERE Id = {ids[obj['key']]};")
    for obj in spec.get("items") or []:
        lines.append(f"DELETE FROM item_template WHERE entry = {ids[obj['key']]};")
    if len(lines) <= 3:
        lines.append("-- (nothing to roll back)")
    return "\n".join(lines) + "\n"


def dbc_delta(spec: dict, *, reserved=None) -> Optional[dict]:
    """DBC delta for objects that declare ``dbc_row: true`` (Item.dbc)."""
    ids = allocate_ids(spec, reserved=reserved)
    rows = []
    for obj in spec.get("items") or []:
        if not obj.get("dbc_row"):
            continue
        disp, _unv = _ref(obj, "display_id")
        rows.append({"id": ids[obj["key"]],
                     "fields": [ids[obj["key"]], 2, 7, -1, 1, disp or 0, 17, 3]})
    if not rows:
        return None
    return {"table": "Item.dbc", "field_count": 8, "rows": rows}


def _cpp_module_identifier(name: str) -> str:
    """Create a valid C++ identifier from a schema-valid module name."""
    identifier = "".join(part.capitalize() for part in name.split("-"))
    return "_" + identifier if identifier[0].isdigit() else identifier


def module_cpp(spec: dict) -> Optional[Dict[str, str]]:
    """Server module sources using AzerothCore's per-module loader contract.

    The pinned module build calls ``Add<directory with hyphens replaced>Scripts``
    from its generated ModulesLoader.cpp; that module-local loader calls the
    declared registration function in the generated shared header.
    """
    module = spec.get("module")
    if not module:
        return None
    name = spec["name"]
    dirname = f"mod-{name}"
    class_name = _cpp_module_identifier(name)
    loader_fn = "Add" + dirname.replace("-", "_") + "Scripts"
    inner_fn = f"Add{class_name}Scripts"
    header_guard = f"ARENA_{dirname.replace('-', '_').upper()}_LOADER_H"
    conf_key = module.get("conf_key", f"{name}.Enable")
    main = f"""// {spec.get('title', name)} — generated server module (Arena Foundry).
// Evidence: ARENA-SYNTHETIC until compiled against the pinned core.
// The server owns all state; this skeleton only registers the script hook.
#include "ScriptMgr.h"
#include "{dirname}.h"

class {class_name}Script : public PlayerScript
{{
public:
    {class_name}Script() : PlayerScript("{class_name}Script") {{}}

    // TODO(verify): wire the real feature hook here. Keep authority server-side:
    // never trust client-supplied ids, counts or cooldowns.
    void OnPlayerLogin(Player* player) override
    {{
        // conf key: {conf_key}
        (void)player;
    }}
}};

void {inner_fn}()
{{
    new {class_name}Script();
}}
"""
    header = f"""// Shared declaration between the generated feature TU and its loader.
#ifndef {header_guard}
#define {header_guard}

void {inner_fn}();

#endif // {header_guard}
"""
    loader = f"""// Per-module entry point; AzerothCore's CMake-generated loader calls this.
#include "{dirname}.h"

void {loader_fn}()
{{
    {inner_fn}();
}}
"""
    conf = f"# {spec.get('title', name)} module configuration\n{conf_key} = 1\n"
    source_dir = f"server/{dirname}/src"
    return {
        f"{source_dir}/{class_name}.cpp": main,
        f"{source_dir}/{dirname}.h": header,
        f"{source_dir}/{dirname}_loader.cpp": loader,
        f"server/{dirname}/conf/{dirname}.conf.dist": conf,
        f"server/{dirname}/README.md": (
            f"# {dirname}\n\nGenerated by Arena Foundry from spec `{name}`.\n"
            f"Loader symbol: `{loader_fn}()`. Config: `{dirname}.conf.dist`.\n"
            f"Install these files under AzerothCore `modules/{dirname}/`; "
            "the `src` and `conf` subdirectories are consumed by its module build.\n"
            "Evidence: ARENA-SYNTHETIC until the pinned-core compile job passes.\n"),
    }


def addon_files(spec: dict) -> Optional[Dict[str, str]]:
    """3.3.5a addon skeleton: .toc + Lua. Presentation only — no authority."""
    addon = spec.get("addon")
    if not addon:
        return None
    name = spec["name"]
    title = addon.get("title", spec.get("title", name))
    prefix = addon.get("prefix", name.upper()[:4])
    toc = (f"## Interface: 30300\n## Title: {title}\n## Version: {spec.get('version', '1.0.0')}\n"
           f"## Notes: Presentation only. The server is authoritative.\n"
           f"## SavedVariables: {prefix}DB\n\n{''.join(p.capitalize() for p in name.split('-'))}.lua\n")
    lua = f"""-- {title} (3.3.5a). Presentation + player intent only.
-- Protocol prefix: {prefix}. The server revalidates everything.
local frame = CreateFrame("Frame", "{prefix}Frame", UIParent)
frame:SetSize(220, 120)
frame:SetPoint("CENTER", UIParent, "CENTER", 0, 0)
frame:SetBackdropBorderColor(0.6, 0.8, 1.0, 1.0)
frame:RegisterEvent("CHAT_MSG_ADDON")
frame:SetScript("OnEvent", function(self, event, prefix, message, dist, sender)
    if prefix ~= "{prefix}" then return end
    -- TODO: render server state; send intents, never decisions.
end)
"""
    base = f"addon/{''.join(p.capitalize() for p in name.split('-'))}"
    return {f"{base}/{''.join(p.capitalize() for p in name.split('-'))}.toc": toc,
            f"{base}/{''.join(p.capitalize() for p in name.split('-'))}.lua": lua}


def config_files(spec: dict) -> Dict[str, str]:
    cfg = spec.get("config") or {}
    if not cfg:
        return {}
    lines = [f"# {spec.get('title', spec['name'])} — generated config (Arena Foundry)"]
    for key in sorted(cfg):
        lines.append(f"{key} = {cfg[key]}")
    return {f"conf/{spec['name']}.conf": "\n".join(lines) + "\n"}


def acceptance_md(spec: dict) -> str:
    rows = spec.get("acceptance") or []
    lines = ["## Acceptance checks", "", "| # | Check | Expected |", "|---|---|---|"]
    for i, check in enumerate(rows, 1):
        if isinstance(check, dict):
            lines.append(f"| {i} | {check.get('check', '')} | {check.get('expected', '')} |")
        else:
            lines.append(f"| {i} | {check} | passes |")
    return "\n".join(lines) + "\n"


def spec_json(spec: dict) -> str:
    return json.dumps(spec, indent=2, sort_keys=True) + "\n"
